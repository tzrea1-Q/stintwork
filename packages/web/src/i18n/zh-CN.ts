export function joinChinese(...segments: (string | number | null | undefined)[]) {
  return segments.reduce<string>((text, value) => {
    const segment = String(value);
    const needsSpace =
      (/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]$/u.test(text) &&
        /^[\x21-\x7e]/.test(segment) &&
        !/^[,.;:!?)\]}]/.test(segment)) ||
      (/[\x21-\x7e]$/.test(text) &&
        !/[([{]$/.test(text) &&
        /^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(segment));
    return text + (needsSpace ? " " : "") + segment;
  }, "");
}

